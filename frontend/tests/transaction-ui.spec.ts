import { test, expect, type Page } from '@playwright/test'
test.skip(process.env.OF_UI_TRANSACTION !== '1', 'Creates a test customer and two test orders in the selected environment.')
const password='DemoUiTest2026!'
const username='ui_test_'+Date.now()
async function login(page:Page,user:string,pass:string) {
  await page.goto('/')
  await page.getByRole('textbox',{name:'用户名'}).fill(user)
  await page.getByLabel('密码',{exact:true}).fill(pass)
  await page.getByRole('button',{name:'登录',exact:true}).click()
  await expect(page.getByRole('navigation',{name:'角色菜单'})).toBeVisible()
}
test('新演示账号的下单支付发货收货和取消',async({page,browser})=>{
  await page.goto('/')
  await page.getByRole('button',{name:'注册顾客账号'}).click()
  await page.getByRole('textbox',{name:'用户名'}).fill(username)
  await page.getByLabel('密码',{exact:true}).fill(password)
  await page.getByLabel('显示名称').fill('UI 验收测试')
  await page.getByRole('button',{name:'注册',exact:true}).click()
  await expect(page.getByText('注册成功，请登录。')).toBeVisible()
  await login(page,username,password)
  const nav=page.getByRole('navigation',{name:'角色菜单'})
  async function addItem(){
    await nav.getByRole('button',{name:'商品目录'}).click()
    await page.getByRole('textbox',{name:'商品名称'}).fill('分隔收纳盒')
    await page.getByRole('button',{name:'搜索',exact:true}).click()
    await page.locator('.product-card').filter({has:page.locator('b').getByText('分隔收纳盒',{exact:true})}).click()
    await page.getByRole('button',{name:'保存到购物车'}).click()
    await expect(page.getByText('购物车已更新。')).toBeVisible()
    await nav.getByRole('button',{name:'我的购物车'}).click()
  }
  await addItem()
  await page.getByRole('button',{name:'添加地址'}).click()
  await page.getByLabel('收件人',{exact:true}).fill('UI测试')
  await page.getByLabel('详细地址',{exact:true}).fill('测试地址')
  await page.getByRole('button',{name:'保存地址'}).click()
  await expect(page.getByRole('button',{name:'提交订单'})).toBeEnabled()
  await page.getByRole('button',{name:'提交订单'}).click()
  const notice=page.getByRole('status').filter({hasText:'已创建'})
  await expect(notice).toBeVisible()
  const orderId=(await notice.innerText()).match(/#(\d+)/)![1]
  await page.getByRole('row').filter({hasText:'#'+orderId}).getByRole('button',{name:'查看订单'}).click()
  await page.getByRole('button',{name:'模拟支付'}).click()
  await expect(page.getByRole('dialog').getByText('待发货')).toBeVisible()
  const merchant=await browser.newPage()
  await login(merchant,'demo_merchant',process.env.DEMO_PASSWORD!)
  await merchant.getByRole('navigation',{name:'角色菜单'}).getByRole('button',{name:'订单处理'}).click()
  const row=merchant.getByRole('row').filter({hasText:'#'+orderId})
  await expect(row).toBeVisible()
  await row.getByRole('button',{name:'查看订单'}).click()
  await merchant.getByLabel('物流单号').fill('UI-TEST-'+orderId)
  await merchant.getByRole('button',{name:'模拟发货'}).click()
  await expect(merchant.getByRole('dialog').getByText('待收货')).toBeVisible()
  await page.getByRole('button',{name:'Close this dialog'}).click()
  await nav.getByRole('button',{name:'我的订单',exact:true}).click()
  await page.getByRole('row').filter({hasText:'#'+orderId}).getByRole('button',{name:'查看订单'}).click()
  await page.getByRole('button',{name:'确认收货'}).click()
  await expect(page.getByRole('dialog').getByText('已完成')).toBeVisible()
  await page.getByRole('button',{name:'Close this dialog'}).click()
  await addItem()
  await page.getByRole('button',{name:'提交订单'}).click()
  await expect(notice).toBeVisible()
  const cancelId=(await notice.innerText()).match(/#(\d+)/)![1]
  await page.getByRole('row').filter({hasText:'#'+cancelId}).getByRole('button',{name:'查看订单'}).click()
  await page.getByRole('button',{name:'取消订单',exact:true}).click()
  await expect(page.getByRole('dialog').getByText('已取消')).toBeVisible()
  console.log(`test customer ${username}; completed ${orderId}; cancelled ${cancelId}`)
})
