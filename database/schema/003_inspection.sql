USE orderflow;
DROP PROCEDURE IF EXISTS inspect_orderflow_triggers;
DELIMITER //
CREATE PROCEDURE inspect_orderflow_triggers()
SQL SECURITY DEFINER READS SQL DATA
BEGIN
  SELECT TRIGGER_NAME, EVENT_MANIPULATION, EVENT_OBJECT_TABLE, ACTION_TIMING, ACTION_STATEMENT
  FROM information_schema.TRIGGERS WHERE TRIGGER_SCHEMA='orderflow';
END//
DELIMITER ;
