CREATE USER IF NOT EXISTS 'of_inspect'@'%' IDENTIFIED BY '@INSPECT_PASSWORD@';
CREATE USER IF NOT EXISTS 'of_replicator'@'%' IDENTIFIED BY '@REPL_PASSWORD@';
